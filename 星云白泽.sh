#!/usr/bin/env bash
# ============================================================
#  Nebula Agent 一键启动（POSIX counterpart of 星云白泽.bat，改为只起看门狗 2026-11-22）
#  一步：起网关看门狗 gw_watchdog.sh。它会在 8099 缺失时自动拉起
#  run_standalone.sh（其内带 while-true 崩溃自愈循环），所以本启动器不再
#  直接起 run_standalone——交给看门狗按需拉起，避免双份启动逻辑。
#  - 不再起 8080 推理引擎：本机可能用在线 API / 其他本地服务。
#  - 看门狗单实例，重复启动自动跳过；已运行的网关也会被它跳过。
#  - 启动完成后本启动器 shell 自然退出（窗自动关闭）；看门狗/网关已脱离本会话。
#  Works on Linux and macOS (Win11 uses 星云白泽.bat).
# ============================================================
AGENT_DIR="$(cd "$(dirname "$0")/Nebula-agent" && pwd)"

echo "==================================================="
echo " Nebula Agent 一键启动（看门狗守护 8099）"
echo "==================================================="

# ---------- 起网关看门狗（它内部已 nohup & 后台化；8099 缺失时自动拉起 run_standalone.sh；单实例）----------
if [ ! -f "$AGENT_DIR/gw_watchdog.sh" ]; then
    echo "错误：未找到看门狗脚本 $AGENT_DIR/gw_watchdog.sh"
    echo "      它是网关缺失时的拉起者，缺失则无网关、无自愈。"
    exit 1
fi
echo "启动网关看门狗（它会在 8099 缺失时自动拉起网关，并持续自愈）..."
bash "$AGENT_DIR/gw_watchdog.sh"

echo "==================================================="
echo " 完成。看门狗已运行；8099 网关将由它在需要时自动拉起。"
echo " 停止：在 $AGENT_DIR 下创建 .gw_stop.flag 软停，或结束对应进程。"
echo " 本地推理如需：请另行自行启动引擎（本脚本不再自动起 8080）。"
echo "==================================================="
