  var lang = DEFAULT_LANG;
  try {
    var saved = localStorage.getItem(STORE_KEY);
    if (saved && LANGS[saved]) lang = saved;
  } catch (e) { /* private mode: fall back to the default */ }

  /* Fall back to the default dictionary, then to the raw key. Returning the key
   * (rather than "") keeps a missing translation visible instead of blanking the UI. */
  function t(key, params) {
    var s = (LANGS[lang] && LANGS[lang][key]);
    if (s == null) s = (LANGS[DEFAULT_LANG] && LANGS[DEFAULT_LANG][key]);
    if (s == null) return key;
    if (params) {
      for (var k in params) {
        if (Object.prototype.hasOwnProperty.call(params, k)) {
          s = s.split("{" + k + "}").join(String(params[k]));
        }
      }
    }
    return s;
  }

  function applyI18n(root) {
    var scope = root || document;
    var i, el, pair, parts;
    var text = scope.querySelectorAll("[data-i18n]");
    for (i = 0; i < text.length; i++) {
      el = text[i];
      el.textContent = t(el.getAttribute("data-i18n"));
    }
    var attrs = scope.querySelectorAll("[data-i18n-attr]");
    for (i = 0; i < attrs.length; i++) {
      el = attrs[i];
      var spec = el.getAttribute("data-i18n-attr") || "";
      var list = spec.split(",");
      for (pair = 0; pair < list.length; pair++) {
        parts = list[pair].split(":");
        if (parts.length === 2) {
          var attr = parts[0].trim();
          var key = parts[1].trim();
          if (attr && key) el.setAttribute(attr, t(key));
        }
      }
    }
    var html = scope.querySelectorAll("[data-i18n-html]");
    for (i = 0; i < html.length; i++) {
      el = html[i];
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    }
  }

  /* Both switchers (header button + About select) are driven from here so they
   * can never drift out of sync. */
  function syncSwitchers() {
    var btn = document.getElementById("lang-btn");
    if (btn) {
      btn.textContent = lang === "zh" ? "EN" : "中";
      btn.setAttribute("title", t("hdr.lang"));
      btn.setAttribute("aria-label", t("hdr.lang"));
    }
    var sel = document.getElementById("lang-select");
    if (sel) sel.value = lang;
  }

  function setLang(next) {
    if (!LANGS[next]) return;
    var changed = next !== lang;
    lang = next;
    try { localStorage.setItem(STORE_KEY, next); } catch (e) { /* in memory only */ }
    document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
    applyI18n();
    syncSwitchers();
    if (changed) {
      document.dispatchEvent(new CustomEvent("strata:langchange", { detail: { lang: next } }));
    }
  }

  function toggleLang() { setLang(lang === "zh" ? "en" : "zh"); }

  window.i18n = {
    t: t,
    applyI18n: applyI18n,
    setLang: setLang,
    toggleLang: toggleLang,
    syncSwitchers: syncSwitchers,
    get lang() { return lang; },
    get defaultLang() { return DEFAULT_LANG; },
    get available() { return Object.keys(LANGS); },
    /* exposed for the key-completeness test */
    _dict: LANGS,
  };
